program = """z*+*+****+*+.z*+*+*+***+*+.z*+*+*+****.z*+*+*+****.z*+*+*+*+**+*+.z*+*+*+**+**.z*+*+*+***+*.z*+*+*****+.z*+*+****+*+.z*+*+***+**+.z*+**+*+*+*+*+.z*+*+*+**+**.z*+*+**+***.z*+*+***+**+.z*+**+*+*+*+*+.z*+*+***+**.z*+*+**+*+*+*+.z*+*+*+**+**+.z*+*+****+*.z*+*+**+*+**.z*+*+***+**+.z*+*+*+***+*.z*+*+*+*+*+**+."""

acc = 0
output = []

for cmd in program:
    if cmd == '*':
        acc *= 2
    elif cmd == '+':
        acc += 1
    elif cmd == 'z':
        acc = 0
    elif cmd == '.':
        output.append(chr(acc))

flag = ''.join(output)
print(flag)